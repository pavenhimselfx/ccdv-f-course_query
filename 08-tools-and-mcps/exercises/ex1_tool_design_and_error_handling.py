async def run_agent(user_message: str) -> str:
    """
    TODO: run one query and return Claude's final text answer.

    1. final_text = ""
    2. async for message in query(prompt=user_message, options=options):
           if isinstance(message, AssistantMessage):
               for block in message.content:
                   if isinstance(block, TextBlock):
                       final_text = block.text
       (query() streams every message in the run - system messages, tool
       calls, tool results, assistant text turns, a final ResultMessage.
       Overwriting final_text each time you see one keeps the LAST assistant
       text block, which is what you want: Claude may "think out loud" or
       call tools across more than one assistant turn before it's done.)
    3. return final_text
    """
    final_text = ""
    async for message in query(prompt=user_message, options=options):
        if isinstance(message, AssistantMessage):
            for block in message.content:
                if isinstance(block, TextBlock):
                    final_text = block.text
    return final_text


