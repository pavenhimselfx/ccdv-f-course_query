# ---------------------------------------------------------------------------
# MOCK BACKEND (already implemented - do not need to change this section)
# ---------------------------------------------------------------------------

MOCK_INVENTORY = {
    "SKU-100": 42,   # widgets
    "SKU-200": 3,    # gadgets (low stock, good for testing insufficient-stock)
    "SKU-300": 0,    # gizmos (out of stock)
}

MOCK_ORDERS = {}
_next_order_id = 1000


class InventoryError(Exception):
    """Raised by the mock backend for any inventory/order problem."""


def backend_lookup_inventory(sku: str) -> int:
    if sku not in MOCK_INVENTORY:
        raise InventoryError(f"Unknown SKU '{sku}'. No such item in inventory.")
    return MOCK_INVENTORY[sku]


def backend_create_order(sku: str, quantity: int, customer_email: str) -> dict:
    global _next_order_id

    if sku not in MOCK_INVENTORY:
        raise InventoryError(f"Unknown SKU '{sku}'. No such item in inventory.")
    if quantity <= 0:
        raise InventoryError("Quantity must be a positive integer.")
    available = MOCK_INVENTORY[sku]
    if quantity > available:
        raise InventoryError(
            f"Insufficient stock for '{sku}': requested {quantity}, "
            f"only {available} available."
        )

    MOCK_INVENTORY[sku] -= quantity
    order_id = f"ORD-{_next_order_id}"
    _next_order_id += 1
    MOCK_ORDERS[order_id] = {
        "order_id": order_id,
        "sku": sku,
        "quantity": quantity,
        "customer_email": customer_email,
        "status": "confirmed",
    }
    return MOCK_ORDERS[order_id]


def backend_get_order_status(order_id: str) -> dict:
    if order_id not in MOCK_ORDERS:
        raise InventoryError(f"Unknown order id '{order_id}'.")
    return MOCK_ORDERS[order_id]


# ---------------------------------------------------------------------------
# PART A: TOOLS (schema + handler + error handling, all in one place)
# ---------------------------------------------------------------------------
#
# The @tool decorator takes (name, description, input_schema_dict). The
# input_schema_dict maps parameter name -> Python type (str, int, float,
# bool...) - the SDK builds the JSON Schema for you from that, which is why
# the description still has to carry everything a plain type annotation
# can't: format, units, what a valid value looks like, when to call this
# tool at all. Same principle as README.md 1.3, just a terser schema shape.

@tool(
    "lookup_inventory",
    "Look up how many units of a given SKU are currently in stock. Read-only "
    "-- does not change inventory or place an order. Call this to check "
    "availability before creating an order, or whenever the user asks how "
    "much stock exists. A SKU looks like 'SKU-100': the literal prefix "
    "'SKU-' followed by digits.",
    {
        "sku": str,
    },
)
async def lookup_inventory(args: dict) -> dict:
    """
    TODO: call backend_lookup_inventory(args["sku"]) inside a try/except.

    On success, return:
        {"content": [{"type": "text", "text": <json.dumps of a useful payload>}]}

    On a caught InventoryError, DO NOT let it propagate - instead return:
        {"content": [{"type": "text", "text": f"Error: {e}"}], "is_error": True}

    This handler should NEVER raise - it's the boundary where a Python
    exception becomes a structured tool result the SDK can hand back to
    Claude. Crashing here is exactly the bug this exercise is about
    avoiding (see README.md 1.4).
    """
    try:
        quantity = backend_lookup_inventory(args["sku"])
        return {
            "content": [
                {
                    "type": "text",
                    "text": json.dumps({"sku": args["sku"], "quantity_in_stock": quantity}),
                }
            ]
        }
    except InventoryError as e:
        return {"content": [{"type": "text", "text": f"Error: {e}"}], "is_error": True}


@tool(
    "create_order",
    "Place an order for a given SKU and quantity, DECREMENTING stock. This "
    "is a mutating, consequential action -- it changes real inventory state "
    "and is not reversible through this tool -- so only call it once the "
    "SKU, quantity, and customer email have all been confirmed with the "
    "user. quantity must be a positive integer no greater than what's "
    "currently in stock; use lookup_inventory first if you're not sure "
    "enough is available.",
    {
        "sku": str,
        "quantity": int,
        "customer_email": str,
    },
)
async def create_order(args: dict) -> dict:
    """TODO: same pattern as lookup_inventory - call
    backend_create_order(**args) in a try/except, return a normal content
    result on success or an is_error result on InventoryError."""
    try:
        order = backend_create_order(
            sku=args["sku"],
            quantity=args["quantity"],
            customer_email=args["customer_email"],
        )
        return {"content": [{"type": "text", "text": json.dumps(order)}]}
    except InventoryError as e:
        return {"content": [{"type": "text", "text": f"Error: {e}"}], "is_error": True}


@tool(
    "get_order_status",
    "Look up the status of a previously created order by its order id. "
    "Read-only -- does not change anything. An order id looks like "
    "'ORD-1000': the literal prefix 'ORD-' followed by digits, as returned "
    "by create_order when an order was placed.",
    {
        "order_id": str,
    },
)
async def get_order_status(args: dict) -> dict:
    """TODO: same pattern again - call backend_get_order_status(args["order_id"])."""
    try:
        order = backend_get_order_status(args["order_id"])
        return {"content": [{"type": "text", "text": json.dumps(order)}]}
    except InventoryError as e:
        return {"content": [{"type": "text", "text": f"Error: {e}"}], "is_error": True}


